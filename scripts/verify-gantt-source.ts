import { strict as assert } from 'node:assert';
import * as source from '../src/pm-gantt-source';
assert.equal(typeof source.parseGanttBlocks, 'function', 'source blocks must be discoverable');
const content = '前言\n```apex-gantt\n{"id":"roadmap","title":"路线","tasks":[{"id":"one","text":"编写","start":"2026-10-21","end":"2026-10-23","kind":"task"}]}\n```\n后记';
const block = source.parseGanttBlocks(content)[0]!;
assert.equal(block.id, 'roadmap');
assert.equal(block.tasks[0]?.text, '编写');
const blankTemplate = source.parseGanttBlocks(source.newGanttSource('空白时间表'))[0]!;
assert.equal(blankTemplate.tasks.length, 0, 'blank timeline template has no prefilled tasks');
const projectTemplate = source.parseGanttBlocks(source.newGanttSource('项目时间表', 'project'))[0]!;
assert.equal(projectTemplate.tasks.length, 6, 'project timeline template includes common phases');
assert.equal(projectTemplate.tasks.filter(task => task.kind === 'milestone').length, 3, 'project template includes milestones');
assert(projectTemplate.tasks.every(task => !task.start && !task.end && !task.deadline), 'template dates remain blank for users to schedule');
const changed = source.updateGanttBlock(content, 'roadmap', 'one', { start: '2026-10-22' });
assert(changed.startsWith('前言\n'));
assert(changed.endsWith('\n后记'));
assert.equal(source.parseGanttBlocks(changed)[0]?.tasks[0]?.start, '2026-10-22');
assert.throws(() => source.updateGanttBlock(content, 'missing', 'one', { start: '2026-10-22' }));
assert.throws(() => source.updateGanttBlock(content, 'roadmap', 'one', { start: '2026-10-25' }));
assert.throws(() => source.parseGanttBlocks(content + '\n' + content));
assert.throws(() => source.parseGanttBlocks(content.replace('2026-10-21', '2026-02-30')));
process.stdout.write('Gantt source assertions passed\n');
assert.equal(typeof source.addGanttTask, 'function', 'standalone timelines must support adding tasks');
const added = source.addGanttTask(content, 'roadmap', '验收', true);
assert.equal(source.parseGanttBlocks(added)[0]?.tasks.length, 2);
const addedId = source.parseGanttBlocks(added)[0]!.tasks[1]!.id!;
const done = source.editGanttTask(added, 'roadmap', addedId, { checked: true, text: '验收完成' });
assert.equal(source.parseGanttBlocks(done)[0]!.tasks[1]!.checked, true);
assert.equal(source.parseGanttBlocks(source.removeGanttTask(done, 'roadmap', addedId))[0]?.tasks.length, 1);

import { renameGanttReferences } from '../src/pm-gantt-rename';
const fm = { immersive: [{ x: 2, y: 3 }], columns: [null, { pm: { ganttSources: 'bad' } }, { pm: { ganttSources: [null, { path: 'Projects/A.md', chartId: 'roadmap' }] } }] };
const renamed = renameGanttReferences(fm, 'Projects', 'Archive');
assert.equal((renamed.columns as typeof fm.columns)[2]?.pm?.ganttSources instanceof Array, true);
assert.equal((renamed.columns as Array<{ pm?: { ganttSources?: unknown[] } }>)[2]?.pm?.ganttSources?.[1] && ((renamed.columns as Array<{ pm: { ganttSources: Array<{ path: string }> } }>)[2]!.pm.ganttSources[1]!.path), 'Archive/A.md');
assert.deepEqual(renamed.immersive, fm.immersive);
assert.equal(renameGanttReferences({ columns: 'bad' }, 'A', 'B').columns, 'bad');
