import { strict as assert } from 'node:assert';
import * as schedule from '../src/pm-schedule';
import { parseTasks } from '../src/pipeline-model';
import { renameProjectTask, parseProjectBody } from '../src/pm-model';
import { parse, serialize } from '../src/parser';
const body = '## 里程碑\n- [ ] 发布 [end:: 2026-10-25] ^apex-release\n## 待办\n- [ ] 编写 [start:: 2026-10-21] [end:: 2026-10-23] [due:: 2026-10-25 12:00] ^apex-write\n';
const task = parseTasks(body)[1] as ReturnType<typeof parseTasks>[number] & { start?: string; end?: string; id?: string };
assert.equal(task.start, '2026-10-21', 'start must be independent from deadline');
assert.equal(task.end, '2026-10-23');
assert.equal(task.due, '2026-10-25 12:00');
assert.equal(task.text, '编写');
assert.equal(task.id, 'apex-write');
assert.equal(parseProjectBody(body).milestones[0]?.text, '发布');
const renamed = renameProjectTask(body, 3, '撰写');
assert(renamed.includes('[start:: 2026-10-21] [end:: 2026-10-23] [due:: 2026-10-25 12:00] ^apex-write'));
assert.equal(typeof schedule.updateSchedule, 'function');
const moved = '前言\n' + body;
const next = schedule.updateSchedule(moved, task, { start: '2026-10-22', end: '2026-10-24' });
assert(next.includes('撰写') === false);
assert(next.includes('[due:: 2026-10-25 12:00]'));
assert.equal(parseTasks(next)[1]?.start, '2026-10-22');
assert.throws(() => schedule.updateSchedule(body, task, { start: '2026-10-26', end: '2026-10-22' }));
assert.throws(() => schedule.updateSchedule(body, task, { start: '2026-02-30' }));
assert.throws(() => schedule.updateSchedule(body.replace('apex-write','missing'), task, { start: '2026-10-22' }));
const cleared = schedule.updateSchedule(body, task, { start: '', end: '' });
assert.equal(parseTasks(cleared)[1]?.start, undefined);
assert.equal(parseTasks(cleared)[1]?.due, '2026-10-25 12:00');
const old = parseTasks('- [ ] 老任务 [scheduled:: 2026-10-21]')[0]!;
assert.equal(old.scheduled, '2026-10-21');
assert.equal(old.due, '2026-10-21', 'legacy calendar contract preserved');
const saved = schedule.updateSchedule('## 待办\n- [ ] 老任务 [scheduled:: 2026-10-21]', { ...old, line: 1 }, { end: '2026-10-25' });
assert(parseTasks(saved)[0]?.id);
assert.equal(schedule.shiftDay('2026-10-31', 1), '2026-11-01');
const board = parse('---\nimmersiveEditable: false\ncolumns:\n  - name: 项目\n    sectionType: pm\n    pm:\n      rootFolder: Projects\n      viewMode: gantt\n      ganttScale: month\n      ganttFilter: milestones\n      ganttProjectPath: "Projects/A.md"\n      ganttCollapsed: ["Projects/A.md"]\n      ganttSources: [{path: "Projects/A.md", chartId: project, kind: chart}, {path: "Projects/A.md", chartId: project, kind: project}]\n---\n## 项目\n');
assert.equal(board.immersiveEditable, false);
assert.equal(board.columns[0]?.pmConfig?.viewMode, 'gantt');
assert.equal(parse(serialize(board)).columns[0]?.pmConfig?.ganttScale, 'month');
assert.equal(parse(serialize(board)).columns[0]?.pmConfig?.ganttFilter, 'milestones');
assert.equal(parse(serialize(board)).columns[0]?.pmConfig?.ganttProjectPath, 'Projects/A.md');
assert.deepEqual(parse(serialize(board)).columns[0]?.pmConfig?.ganttSources?.map(ref => ref.kind), ['chart', 'project']);
assert.equal(parse(serialize(board)).immersiveEditable, false);
process.stdout.write('PM schedule assertions passed\n');
import { planDashboardUpdate } from '../src/render-update';
assert.equal(planDashboardUpdate(board, { ...board, immersiveEditable: true }, 'local').kind, 'full', 'unlocking must update controls even if geometry is unchanged');
assert.equal(parseTasks('```md\n- [ ] 示例 [start:: 2026-10-21]\n```').length, 0, 'examples are not project tasks');
assert.throws(() => schedule.updateSchedule(next, task, { start: '2026-10-23' }), 'stale edits to the same field must be rejected');
const merged = schedule.updateSchedule(next, task, { due: '2026-10-26' });
assert.equal(parseTasks(merged)[1]?.start, '2026-10-22', 'editing deadline preserves concurrently changed start');
import { scanFileTasks } from '../src/alltasks-scan';
assert.equal(scanFileTasks({ path: 'P.md', stat: { mtime: 1, ctime: 1 } } as never, body)[1]?.text, '编写', 'internal block IDs must not leak into calendar labels');
